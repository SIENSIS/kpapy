<?php

declare(strict_types=1);

namespace Kpapy\Demo;

use Kpapy\Config\Kpapy;
use Kpapy\Demo\Libraries\DemoPermissions;
use Kpapy\Demo\Libraries\DemoTotp;

/**
 * kpapy settings of the demo, independent of the host project's app/Config/Kpapy.php.
 */
class DemoConfig extends Kpapy
{
    public int $perPage = 5;

    /**
     * Every id in the demo API is masked (with the demo's own key).
     */
    public bool $maskIds = true;

    public ?string $permissionResolver = DemoPermissions::class;

    public bool $denyByDefault = true;

    /**
     * The admin uses an authenticator app (TOTP, simulated on its profile page);
     * the reader has no 2FA, so the code is shown in its web profile.
     */
    public array $twoFactorMethods = ['totp', 'web'];

    public array $twoFactorProviders = [
        'totp' => DemoTotp::class,
        'web'  => \Kpapy\Auth\TwoFactor\WebCodeProvider::class,
    ];

    public array $localeFallbacks = ['en'];

    public string $openApiTitle       = 'kpapy demo library';
    public string $openApiDescription = 'Demo API generated by kpapy: books, authors, tags and the loans of the signed-in user.';

    public function __construct()
    {
        parent::__construct();

        $this->maskKey    = (string) (Demo::marker()['mask_key'] ?? str_repeat('0', 64));
        $this->profileUrl = Demo::url('profile/reader');
    }
}
